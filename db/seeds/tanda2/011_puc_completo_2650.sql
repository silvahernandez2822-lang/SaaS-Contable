-- (las discrepancias de nombre detectadas están listadas en el reporte).
--
-- El último bloque corrige permite_movimiento=false en las cuentas que
-- tanda2 dejó como imputables y que este catálogo dota de subcuentas — solo
-- si no tienen movimientos ni conceptos activos (para no chocar con los
-- guardias PU003/PU005 de la migración 179 al re-ejecutar sobre una base viva).
