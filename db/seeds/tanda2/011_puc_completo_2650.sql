--   · nivel      : por longitud del código (1→1, 2→2, 4→3, 6→4).
--   · parent_id  : por prefijo del código (resuelto por subconsulta).
--   · naturaleza : por clase; se invierte en (a) contra-activos de clase 1
--       (12/13/14/15/16/17/18 · 99 provisiones, 1592/1596/1597/1598
